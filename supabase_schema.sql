-- ==========================================
-- 8. SERVER-SIDE XP
-- The browser can no longer write xp/level or xp_awarded; XP is computed here from the saved exercises.
-- Volume rule must match calculateVolume() in src/lib/utils.js.
-- ==========================================
REVOKE INSERT, UPDATE ON profiles FROM anon, authenticated;
GRANT INSERT (id, display_name, color, updated_at) ON profiles TO authenticated;
GRANT UPDATE (display_name, color, updated_at) ON profiles TO authenticated;

REVOKE INSERT, UPDATE ON workouts FROM anon, authenticated;
GRANT INSERT (user_id, day_of_week, routine_name, is_rest_day, completed, completed_at) ON workouts TO authenticated;
GRANT UPDATE (day_of_week, routine_name, is_rest_day, completed_at) ON workouts TO authenticated;

CREATE OR REPLACE FUNCTION public.workout_xp(p_workout_id BIGINT)
RETURNS INTEGER LANGUAGE sql STABLE SET search_path = public AS $$
  SELECT 50 + floor(COALESCE(SUM(
    CASE WHEN jsonb_typeof(e.logged_sets) = 'object' AND e.logged_sets <> '{}'::jsonb THEN
      (SELECT SUM(COALESCE(substring(s.value->>'reps' from '\d+')::numeric, 0)
                * COALESCE(substring(s.value->>'weight' from '^\s*(-?\d*\.?\d+)')::numeric, 0))
       FROM jsonb_each(e.logged_sets) s)
    ELSE COALESCE(e.sets, 0) * COALESCE(substring(e.reps from '\d+')::numeric, 0) * COALESCE(e.weight, 0)
    END), 0) / 100)::int
  FROM exercises e WHERE e.workout_id = p_workout_id;
$$;

-- Awards XP for one finished workout, at most once
CREATE OR REPLACE FUNCTION public.award_workout_xp(p_workout_id BIGINT)
RETURNS JSON LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_gain INTEGER; v_level INTEGER;
BEGIN
  UPDATE workouts SET xp_awarded = workout_xp(p_workout_id)
  WHERE id = p_workout_id AND user_id = auth.uid() AND completed AND xp_awarded IS NULL
  RETURNING xp_awarded INTO v_gain;
  IF NOT FOUND THEN RAISE EXCEPTION 'Workout not found or XP already awarded'; END IF;

  UPDATE profiles SET xp = xp + v_gain, level = floor(sqrt((xp + v_gain) / 100.0))::int + 1
  WHERE id = auth.uid()
  RETURNING level INTO v_level;

  RETURN json_build_object('xp_gained', v_gain, 'new_level', v_level);
END;
$$;

-- Undo: deletes a finished workout and takes back exactly the XP it was given
CREATE OR REPLACE FUNCTION public.revoke_workout_xp(p_workout_id BIGINT)
RETURNS INTEGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_xp INTEGER;
BEGIN
  DELETE FROM workouts WHERE id = p_workout_id AND user_id = auth.uid() AND completed
  RETURNING COALESCE(xp_awarded, 0) INTO v_xp;
  IF NOT FOUND THEN RAISE EXCEPTION 'Workout not found'; END IF;

  UPDATE profiles SET xp = GREATEST(0, xp - v_xp), level = floor(sqrt(GREATEST(0, xp - v_xp) / 100.0))::int + 1
  WHERE id = auth.uid();
  RETURN v_xp;
END;
$$;

-- ==========================================
-- 9. FINISH WORKOUT (offline-safe)
-- Saves a whole finished workout in one transaction. Workouts in progress live on the phone.
-- ==========================================
CREATE OR REPLACE FUNCTION public.finish_workout(
  p_client_id UUID, p_template_id BIGINT, p_routine_name TEXT, p_day_of_week TEXT,
  p_completed_at TIMESTAMPTZ, p_exercises JSONB, p_removed_from_plan BIGINT[] DEFAULT '{}')
RETURNS JSON LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_id BIGINT; v_xp INTEGER; v_award JSON;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not signed in'; END IF;

  -- A retry of a finish that already went through: return what was saved
  SELECT id, xp_awarded INTO v_id, v_xp FROM workouts WHERE client_id = p_client_id AND user_id = auth.uid();
  IF FOUND THEN
    RETURN json_build_object('workout_id', v_id, 'xp_gained', v_xp,
      'new_level', (SELECT level FROM profiles WHERE id = auth.uid()), 'already_saved', TRUE);
  END IF;

  IF p_completed_at > now() + INTERVAL '1 hour' THEN RAISE EXCEPTION 'Workout date is in the future'; END IF;

  INSERT INTO workouts (user_id, day_of_week, routine_name, completed, completed_at, client_id)
  VALUES (auth.uid(), p_day_of_week, COALESCE(NULLIF(p_routine_name, ''), 'Workout'), TRUE, p_completed_at, p_client_id)
  RETURNING id INTO v_id;

  INSERT INTO exercises (workout_id, name, sets, reps, weight, minutes, logged_sets, completed)
  SELECT v_id, x->>'name', COALESCE((x->>'sets')::int, 0), COALESCE(x->>'reps', '0'),
         COALESCE((x->>'weight')::numeric, 0), COALESCE((x->>'minutes')::int, 0),
         NULLIF(x->'logged_sets', 'null'::jsonb), TRUE
  FROM jsonb_array_elements(p_exercises) x;

  IF EXISTS (SELECT 1 FROM workouts WHERE id = p_template_id AND user_id = auth.uid() AND NOT completed) THEN
    -- Planned reps/weight go back to the plan; a swap made with "Update my plan" ('replace') takes the old one's place
    UPDATE exercises AS t
    SET reps = COALESCE(x->>'reps', t.reps), weight = COALESCE((x->>'weight')::numeric, t.weight),
        name = CASE WHEN x->>'plan_change' = 'replace' THEN COALESCE(NULLIF(x->>'name', ''), t.name) ELSE t.name END,
        sets = CASE WHEN x->>'plan_change' = 'replace' THEN COALESCE((x->>'sets')::int, t.sets) ELSE t.sets END,
        minutes = CASE WHEN x->>'plan_change' = 'replace' THEN COALESCE((x->>'minutes')::int, t.minutes) ELSE t.minutes END,
        completed = FALSE, logged_sets = NULL
    FROM jsonb_array_elements(p_exercises) x
    WHERE t.workout_id = p_template_id AND t.id = (x->>'template_exercise_id')::bigint;

    -- Exercises added mid-workout join the plan only when asked ('add'). Workouts queued by older app
    -- versions have no plan_change and keep the old always-add. Names already planned are skipped (Undo, then finish again).
    INSERT INTO exercises (workout_id, name, sets, reps, weight, minutes)
    SELECT p_template_id, x->>'name', COALESCE((x->>'sets')::int, 0), COALESCE(x->>'reps', '0'),
           COALESCE((x->>'weight')::numeric, 0), COALESCE((x->>'minutes')::int, 0)
    FROM jsonb_array_elements(p_exercises) x
    WHERE x->>'template_exercise_id' IS NULL
      AND (x->>'plan_change' = 'add' OR NOT x ? 'plan_change')
      AND NOT EXISTS (SELECT 1 FROM exercises e WHERE e.workout_id = p_template_id AND lower(e.name) = lower(x->>'name'));

    -- Removed mid-workout with "Remove from my plan too"
    DELETE FROM exercises WHERE workout_id = p_template_id AND id = ANY (COALESCE(p_removed_from_plan, '{}'));
  END IF;

  v_award := award_workout_xp(v_id);
  RETURN json_build_object('workout_id', v_id, 'xp_gained', (v_award->>'xp_gained')::int,
    'new_level', (v_award->>'new_level')::int, 'already_saved', FALSE);
END;
$$;

-- ==========================================
-- 10. REARRANGE WEEK (Planner)
-- Moves plans to new days in one transaction. The browser can't write created_at itself.
-- p_moves: [{id, day_of_week}]. p_blank_days: days left without a plan, which get a blank one.
-- ==========================================
CREATE OR REPLACE FUNCTION public.rearrange_week(p_moves JSONB, p_blank_days TEXT[])
RETURNS VOID LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_moved INTEGER;
  v_days CONSTANT TEXT[] := ARRAY['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'Not signed in'; END IF;
  IF EXISTS (SELECT 1 FROM jsonb_array_elements(p_moves) x WHERE NOT (x->>'day_of_week' = ANY (v_days)))
     OR NOT (COALESCE(p_blank_days, '{}') <@ v_days) THEN
    RAISE EXCEPTION 'Unknown day';
  END IF;

  -- created_at = now(): the newest plan on a day is the one shown, so the moved plan wins over older rows there
  UPDATE workouts w SET day_of_week = x->>'day_of_week', created_at = now()
  FROM jsonb_array_elements(p_moves) x
  WHERE w.id = (x->>'id')::bigint AND w.user_id = auth.uid() AND NOT w.completed;
  GET DIAGNOSTICS v_moved = ROW_COUNT;
  IF v_moved <> jsonb_array_length(p_moves) THEN RAISE EXCEPTION 'Plan not found'; END IF;

  INSERT INTO workouts (user_id, day_of_week) SELECT auth.uid(), d FROM unnest(p_blank_days) d;
END;
$$;
