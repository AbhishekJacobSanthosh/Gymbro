CREATE POLICY "Achievements viewable by everyone" ON achievements FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Users insert own achievements" ON achievements FOR INSERT WITH CHECK (auth.uid() = user_id);
