CREATE POLICY "Activities viewable by everyone" ON activity_feed FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Users insert own activities" ON activity_feed FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Streak Freezes: Anyone authenticated can view, owner has full control
CREATE POLICY "Streak freezes viewable by everyone" ON streak_freezes FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "Users insert own streak_freezes" ON streak_freezes FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users update own streak_freezes" ON streak_freezes FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "Users delete own streak_freezes" ON streak_freezes FOR DELETE USING (auth.uid() = user_id);

